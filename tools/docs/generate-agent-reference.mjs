#!/usr/bin/env node
/**
 * Generates the coding-agent reference surfaces consumed by humans and LLM
 * agents:
 *   projects/docs/public/llms.md  (hand-written header/footer + generated
 *                                  entry-point map and component reference)
 *   projects/docs/public/llms.txt (generated manifest with canonical links)
 *
 * Inputs are committed data: the docs registry (docs-registry-lib.mjs), the component
 * inventory, and the hand-written narrative in tools/docs/agent-reference/.
 * Outputs are committed so the docs build needs no prebuild step; drift is
 * caught in CI via --check (part of verify:docs).
 *
 * Usage:
 *   node tools/docs/generate-agent-reference.mjs          # regenerate
 *   node tools/docs/generate-agent-reference.mjs --check  # fail on drift
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import {
  buildReferenceContext,
  renderAgentReference,
  renderLlmsTxt,
} from './agent-reference-lib.mjs';
import { loadDocsRegistry } from './docs-registry-lib.mjs';

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../..',
);
const canonicalBase = 'https://orchestra.ciag.org.br';
const narrativeDir = path.join(root, 'tools/docs/agent-reference');
const notesDir = path.join(narrativeDir, 'notes');
const llmsMdPath = path.join(root, 'projects/docs/public/llms.md');
const llmsTxtPath = path.join(root, 'projects/docs/public/llms.txt');

const check = process.argv.includes('--check');

const inventory = JSON.parse(
  fs.readFileSync(path.join(root, 'docs/quality/inventory.json'), 'utf8'),
);
const registry = loadDocsRegistry(root);
if (registry.problems.length) {
  console.error(
    'Docs registry is invalid; run `npm run verify:docs-registry` for details.',
  );
  process.exit(1);
}
const entries = registry.entries;
const usageDocs = Object.fromEntries(
  entries
    .filter((entry) => entry.packagePath)
    .map((entry) => [entry.id, { packagePath: entry.packagePath }]),
);
const contentDocs = Object.fromEntries(
  registry.content.map((family) => [family.id, family.doc.i18n['pt-BR']]),
);
const packageVersion = JSON.parse(
  fs.readFileSync(path.join(root, 'projects/orc-ds/package.json'), 'utf8'),
).version;

const header = fs.readFileSync(path.join(narrativeDir, 'header.md'), 'utf8');
const footer = fs.readFileSync(path.join(narrativeDir, 'footer.md'), 'utf8');
const notes = {};
for (const file of fs.existsSync(notesDir)
  ? fs
      .readdirSync(notesDir)
      .filter((name) => name.endsWith('.md'))
      .sort()
  : []) {
  notes[path.basename(file, '.md')] = fs.readFileSync(
    path.join(notesDir, file),
    'utf8',
  );
}

const context = buildReferenceContext(
  inventory,
  entries,
  canonicalBase,
  usageDocs,
  contentDocs,
);

const generatedHeader = [
  '<!-- Generated by tools/docs/generate-agent-reference.mjs from the docs',
  '     catalog and component inventory. Hand-written narrative lives in',
  '     tools/docs/agent-reference/ (header.md, footer.md, notes/<family>.md).',
  '     Run `npm run docs:generate-agent-reference` after API or catalog changes. -->',
  '',
].join('\n');

async function format(source, filepath) {
  const config = {
    ...(await prettier.resolveConfig(filepath, { editorconfig: true })),
    filepath,
  };
  return prettier.format(source, config);
}

// The committed output must survive `prettier --check` unchanged, so the
// generator formats through the same prettier config the repo gates use.
const llmsMd = await format(
  generatedHeader +
    renderAgentReference({
      header,
      footer,
      notes,
      context,
      entryPoints: inventory.entryPoints,
      version: packageVersion,
    }),
  llmsMdPath,
);
const llmsTxt = renderLlmsTxt({ canonicalBase });

if (check) {
  const stale = [];
  if (fs.readFileSync(llmsMdPath, 'utf8') !== llmsMd)
    stale.push(path.relative(root, llmsMdPath));
  if (fs.readFileSync(llmsTxtPath, 'utf8') !== llmsTxt)
    stale.push(path.relative(root, llmsTxtPath));
  if (stale.length) {
    console.error(
      'Stale agent reference files. Run: npm run docs:generate-agent-reference',
    );
    for (const file of stale) console.error(`  ${file}`);
    process.exit(1);
  }
  console.log(
    `agent reference up to date (${inventory.entryPoints.length} entry points, ${entries.length} documented families).`,
  );
  process.exit(0);
}

fs.writeFileSync(llmsMdPath, llmsMd);
fs.writeFileSync(llmsTxtPath, llmsTxt);
console.log(
  `wrote ${path.relative(root, llmsMdPath)} (${inventory.entryPoints.length} entry points, ${entries.length} documented families) and ${path.relative(root, llmsTxtPath)}.`,
);
