import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const inventory = JSON.parse(
  fs.readFileSync(path.join(root, 'docs/quality/inventory.json'), 'utf8'),
);
const components = inventory.declarations.filter(
  (item) => item.kind === 'Component',
);
const imports = components.map(
  (item, index) =>
    `import { ${item.name} as Component${index} } from './${item.file.replace('projects/orc-ds/', '').replace(/\.ts$/, '')}';`,
);
const cases = components.map(
  (item, index) =>
    `  { name: ${JSON.stringify(`${item.name} (${path.dirname(item.file).replace('projects/orc-ds/', '')})`)}, type: Component${index} as Type<unknown>, required: ${JSON.stringify(item.inputs.filter((input) => input.required).map((input) => input.publicName ?? input.name))} },`,
);
const source = `// Generated by tools/quality/generate-lifecycle-tests.mjs. Functional suites complement this exhaustive lifecycle check.
import { Type } from '@angular/core';
import { TestBed } from '@angular/core/testing';
import { provideRouter } from '@angular/router';
${imports.join('\n')}

const components = [
${cases.join('\n')}
];

function requiredValue(name: string): unknown {
  switch (name) {
    case 'ariaLabel': return 'Test action';
    case 'item': return { id: 'navigation-item', label: 'Home', href: '#' };
    case 'fileData': return { id: 'test-file', name: 'document.txt', type: 'text/plain', size: 4, file: new File(['test'], 'document.txt'), progress: 0, status: 'pending' };
    case 'toast': return { id: 'test-toast', type: 'info', title: 'Notification', message: 'Message', duration: 0, dismissible: true, showIcon: true, position: 'top-right', pauseOnHover: true, createdAt: 0 };
    default: throw new Error('Add a meaningful fixture for required input ' + name);
  }
}

describe('Every component: rendering, instance isolation and teardown', () => {
  for (const entry of components) {
    it(entry.name, () => {
      TestBed.configureTestingModule({ providers: [provideRouter([])] });
      const fixtures = [TestBed.createComponent(entry.type), TestBed.createComponent(entry.type)];
      for (const fixture of fixtures) {
        for (const name of entry.required) fixture.componentRef.setInput(name, requiredValue(name));
        fixture.detectChanges();
      }
      const ids = fixtures.flatMap(fixture => Array.from((fixture.nativeElement as HTMLElement).querySelectorAll('[id]')).map(element => element.id)).filter(Boolean);
      expect(new Set(ids).size).withContext('Rendered IDs must be unique within and across instances').toBe(ids.length);
      for (const fixture of fixtures) expect(() => fixture.destroy()).not.toThrow();
    });
  }
});
`;
fs.writeFileSync(
  path.join(root, 'projects/orc-ds/all-components-lifecycle.spec.ts'),
  source,
);
console.log(
  `Generated lifecycle and ID isolation tests for all ${components.length} component implementations.`,
);
